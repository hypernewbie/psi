#!/usr/bin/env node
// Renders Markdown samples with the pinned Pi renderer and writes the parity
// fixtures used by internal/terminal/markdown_parity_test.go.
//
// The Pi checkout lives in temp/pi-mono (gitignored). Its Markdown component
// imports sibling modules that pull in terminal and theme code, so the script
// copies the component into a scratch directory, replaces those imports with
// small stubs, and renders the samples with a theme that emits no SGR.
//
// Usage:
//   npm --prefix temp/pi-md install marked@18.0.11 marked-cjk-friendly@0.1.2 get-east-asian-width@1.6.0
//   node scripts/pi-markdown-reference.mjs internal/terminal/testdata/pi-markdown-samples.json \
//     internal/terminal/testdata/pi-markdown-parity.json
//
// Pi renders assistant prose with a two cell margin on both sides. psi uses
// the same left margin and reserves one cell for terminal autowrap, so the
// recorded psi width is one cell smaller than the Pi width.

import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const piSource = join(repoRoot, "temp", "pi-mono", "packages", "tui", "src");
const scratch = join(repoRoot, "temp", "pi-md");
const refDir = join(scratch, "ref");

const samplesPath = resolve(process.argv[2] ?? join(repoRoot, "internal/terminal/testdata/pi-markdown-samples.json"));
const outputPath = resolve(process.argv[3] ?? join(repoRoot, "internal/terminal/testdata/pi-markdown-parity.json"));

rmSync(refDir, { recursive: true, force: true });
mkdirSync(refDir, { recursive: true });

cpSync(join(piSource, "utils.ts"), join(refDir, "utils.ts"));
cpSync(join(piSource, "components", "markdown.ts"), join(refDir, "markdown.ts"));

const markdownPath = join(refDir, "markdown.ts");
const markdownSource = readFileSync(markdownPath, "utf8")
	.replace('from "../latex.ts"', 'from "./latex.ts"')
	.replace('from "../terminal-image.ts"', 'from "./terminal-image.ts"')
	.replace('from "../tui.ts"', 'from "./tui.ts"')
	.replace('from "../utils.ts"', 'from "./utils.ts"');
writeFileSync(markdownPath, markdownSource);

writeFileSync(
	join(refDir, "latex.ts"),
	"export function renderLatex(_text: string, _opts?: { display?: boolean }): string | null {\n\treturn null;\n}\n",
);
writeFileSync(
	join(refDir, "terminal-image.ts"),
	[
		"export function getCapabilities(): { images: null; trueColor: boolean; hyperlinks: boolean } {",
		"\treturn { images: null, trueColor: false, hyperlinks: false };",
		"}",
		"export function hyperlink(text: string, _href: string): string {",
		"\treturn text;",
		"}",
		"export function isImageLine(_line: string): boolean {",
		"\treturn false;",
		"}",
		"",
	].join("\n"),
);
writeFileSync(
	join(refDir, "tui.ts"),
	[
		"export interface Component {",
		"\trender(width: number): string[];",
		"\tinvalidate?(): void;",
		"}",
		"",
	].join("\n"),
);

const { Markdown } = await import(pathToFileURL(join(refDir, "markdown.ts")).href);

const identity = (text) => text;
const theme = {
	heading: identity,
	link: identity,
	linkUrl: identity,
	code: identity,
	codeBlock: identity,
	codeBlockBorder: identity,
	quote: identity,
	quoteBorder: identity,
	hr: identity,
	listBullet: identity,
	bold: identity,
	italic: identity,
	strikethrough: identity,
	underline: identity,
};

const samples = JSON.parse(readFileSync(samplesPath, "utf8"));
const fixtures = samples.map((sample) => {
	const markdown = new Markdown(sample.text, 2, 0, theme);
	const lines = markdown.render(sample.width).map((line) => line.replace(/\x1b\[[0-9;]*m/g, ""));
	return {
		name: sample.name,
		text: sample.text,
		width: sample.width - 1,
		lines,
	};
});

writeFileSync(
	outputPath,
	`${JSON.stringify(
		{
			reference:
				"Pi Markdown component at d5b3de22d0e24a3e9c38a9410d3329b099717283 (packages/tui/src/components/markdown.ts)",
			note: "Generated by scripts/pi-markdown-reference.mjs. Pi renders with a two cell margin; psi reserves one cell for autowrap.",
			fixtures,
		},
		null,
		1,
	)}\n`,
);
console.log(`wrote ${fixtures.length} fixtures to ${outputPath}`);
